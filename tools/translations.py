def build(t: dict[str, str]) -> dict:
    """Nested translation file in the same shape as en.json."""

    def preset(n: int) -> str:
        return f"{t['preset']} {n}"

    def custom(n: int) -> str:
        return f"{t['custom']} {n}"

    return {
        "config": {
            "flow_title": "{name}",
            "step": {
                "user": {"description": t["user"], "data": {"address": t["address"]}},
                "pair": {
                    "title": t["pair_title"],
                    "description": f"{t['pair_intro']}\n\n1. {t['pair_1']}\n2. {t['pair_2']}\n3. {t['pair_3']}",
                },
                "reauth_confirm": {"title": t["reauth_title"], "description": t["reauth"]},
            },
            "error": {
                "device_not_found": t["err_not_found"],
                "cannot_connect": t["err_connect"],
                "pairing_failed": t["err_pairing"],
            },
            "abort": {
                "already_configured": t["ab_configured"],
                "no_devices_found": t["ab_no_devices"],
                "not_supported": t["ab_not_supported"],
                "reauth_successful": t["ab_reauth"],
                "already_in_progress": t["ab_in_progress"],
            },
        },
        "entity": {
            "number": {
                key: {"name": t[src]}
                for key, src in (
                    ("brightness", "brightness"),
                    ("focus", "focus"),
                    ("keystone", "keystone"),
                    ("picture_brightness", "picture_brightness"),
                    ("picture_contrast", "picture_contrast"),
                    ("picture_saturation", "picture_saturation"),
                    ("picture_sharpness", "picture_sharpness"),
                    ("white_balance_red", "wb_red"),
                    ("white_balance_green", "wb_green"),
                    ("white_balance_blue", "wb_blue"),
                )
            },
            "select": {
                "rotation": {
                    "name": t["rotation"],
                    "state": {
                        "normal": t["normal"],
                        "rotate_180": t["rotate_180"],
                        "mirror_horizontal": t["mirror_h"],
                        "mirror_vertical": t["mirror_v"],
                    },
                },
                "picture_mode": {
                    "name": t["picture_mode"],
                    "state": {
                        "preset_1": preset(1),
                        "preset_2": preset(2),
                        "preset_3": preset(3),
                        "custom_1": custom(1),
                        "custom_2": custom(2),
                    },
                },
            },
            "sensor": {
                "charge_state": {
                    "name": t["charge_state"],
                    "state": {"on_battery": t["on_battery"], "charging": t["charging"], "full": t["full"]},
                },
                "smartphones_added": {"name": t["smartphones_added"]},
            },
            "switch": {
                "auto_brightness": {"name": t["auto_brightness"]},
                "auto_focus": {"name": t["auto_focus"]},
                "auto_rotation": {"name": t["auto_rotation"]},
                "xloud": {"name": "xLOUD"},
                "restrict_adding_smartphones": {"name": t["restrict_adding"]},
            },
            "button": {
                "keystone_reset": {"name": t["reset_keystone"]},
                "picture_reset": {"name": t["reset_picture"]},
            },
        },
        "exceptions": {
            "device_not_found": {"message": t["x_not_found"]},
            "not_paired": {"message": t["x_not_paired"]},
            "projector_busy": {"message": t["x_busy"]},
            "communication_error": {"message": t["x_comm"]},
        },
    }


def main() -> None:
    for lang, table in LANGUAGES.items():
        path = TRANSLATIONS / f"{lang}.json"
        path.write_text(json.dumps(build(table), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print("wrote", path.name)


if __name__ == "__main__":
    main()
