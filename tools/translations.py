def main() -> None:
    for lang, table in LANGUAGES.items():
        path = TRANSLATIONS / f"{lang}.json"
        path.write_text(json.dumps(build(table), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print("wrote", path.name)


if __name__ == "__main__":
    main()
